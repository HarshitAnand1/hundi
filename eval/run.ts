/**
 * Scores verifyInvoice against the answer key in eval/cases.json and writes eval/RESULTS.md.
 * Deterministic: no model is called. An LLM signal, where a case has one, is given as data.
 * Usage: pnpm eval
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toBytes } from "viem";
import { verifyInvoice, type InvoiceInput, type VerifyInvoiceInput } from "../packages/sdk/src/index.js";
import {
  DAY,
  NOW,
  baseInvoice,
  deps,
  po,
  sellerAcct,
  signedInput,
  strangerAcct,
} from "../packages/sdk/test/fixtures.js";

const here = dirname(fileURLToPath(import.meta.url));
interface Case {
  id: string;
  category: string;
  description: string;
  invoice: Record<string, unknown>;
  context: {
    signer?: "stranger";
    attester?: "stranger";
    noDelivery?: boolean;
    humanApproved?: boolean;
    llmFlag?: boolean;
    dupKey?: boolean;
    vendorMissing?: boolean;
    poAmount?: string;
    tamperAmount?: string;
  };
  expect: string[];
}
const key = JSON.parse(readFileSync(join(here, "cases.json"), "utf8")) as { cases: Case[] };

function resolve(v: unknown): unknown {
  if (typeof v === "string") {
    if (v === "$SELLER") return sellerAcct.address;
    if (v === "$SELLER_LC") return sellerAcct.address.toLowerCase();
    if (v === "$ATTACKER") return strangerAcct.address;
    if (v === "$OTHERGOODS") return keccak256(toBytes("40 cartons, polyester, lot 9"));
    const m = /^\$NOW([+-]\d+)d$/.exec(v);
    if (m) return NOW + Number(m[1]) * DAY;
    return v;
  }
  if (v && typeof v === "object" && !Array.isArray(v)) {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolve(x)]));
  }
  return v;
}

async function build(c: Case): Promise<[VerifyInvoiceInput, ReturnType<typeof deps>]> {
  const inv = { ...baseInvoice(), ...(resolve(c.invoice) as object) } as InvoiceInput;
  const x = c.context;
  let input: VerifyInvoiceInput;
  try {
    input = await signedInput(inv, { ...(x.signer ? { signer: strangerAcct } : {}), ...(x.attester ? { attester: strangerAcct } : {}) });
  } catch {
    input = { invoice: inv, sellerSignature: "0x" }; // unparseable invoice: cannot even be signed canonically
  }
  if (x.tamperAmount) input = { ...input, invoice: { ...inv, amount: x.tamperAmount } };
  if (x.noDelivery) delete input.delivery;
  if (x.humanApproved !== undefined) input.humanApproved = x.humanApproved;
  if (x.llmFlag !== undefined) input.llm = { flagged: x.llmFlag, ...(x.llmFlag ? { reason: "model flagged manipulative instructions" } : {}) };
  const d = deps({
    ...(x.dupKey ? { isInvoiceKeyUsed: () => true } : {}),
    ...(x.vendorMissing ? { getVendor: () => undefined } : {}),
    ...(x.poAmount ? { getPurchaseOrder: (r: string) => (r === po.poReference ? { ...po, amount: BigInt(x.poAmount!) } : undefined) } : {}),
  });
  return [input, d];
}

const rows: string[] = [];
let pass = 0;
let falseAccept = 0;
let falseRefuse = 0;
for (const c of key.cases) {
  const [input, d] = await build(c);
  const r = await verifyInvoice(input, d);
  const got = r.ok ? [] : r.refusals.map((x) => x.code);
  const ok = JSON.stringify(got) === JSON.stringify(c.expect);
  if (ok) pass++;
  if (r.ok && c.expect.length) falseAccept++;
  if (!r.ok && !c.expect.length) falseRefuse++;
  rows.push(`| ${c.id} | ${c.category} | ${c.description} | ${c.expect.join(", ") || "accept"} | ${got.join(", ") || "accept"} | ${ok ? "✓" : "✗"} |`);
}

const total = key.cases.length;
const summary = `${pass}/${total} exact matches · ${falseAccept} false accepts · ${falseRefuse} false refusals`;
const md = [
  "# Eval results",
  "",
  "Generated by `pnpm eval` from `eval/cases.json` (answer key committed before results).",
  "Scores `verifyInvoice` only; deterministic, no model call. Exact match = same refusal codes in spec order.",
  "",
  `**${summary}**`,
  "",
  "| Case | Category | Description | Expected | Got | |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows,
  "",
].join("\n");
writeFileSync(join(here, "RESULTS.md"), md);
console.log(summary);
process.exit(pass === total ? 0 : 1);
